/**
 * In-app notification inbox. Populated by domain-event handlers (see src/server/events.ts);
 * email / push / WhatsApp channels can be added as further handlers without schema changes.
 */
export const notifications = pgTable(
  "notifications",
  {
    id: id(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    type: varchar("type", { length: 60 }).notNull(),
    title: varchar("title", { length: 160 }).notNull(),
    body: text("body"),
    data: jsonb("data").$type<Record<string, unknown>>(),
    readAt: timestamp("read_at", { withTimezone: true }),
    createdAt: createdAt(),
  },
  (t) => [index("notifications_user_created_idx").on(t.userId, t.createdAt)],
);

/* ───────────────────────────── site-wide settings & private files ───────────────────────────── */

/**
 * Singleton row (id = 1). The site access code is stored encrypted (AES-256-GCM with AUTH_SECRET)
 * so the coach can view and share it; `access_version` rotates on every change, which instantly
 * invalidates every previously issued access cookie.
 */
export const siteSettings = pgTable(
  "site_settings",
  {
    id: smallint("id").primaryKey().default(1),
    accessCodeEnc: text("access_code_enc"),
    accessVersion: uuid("access_version").notNull().defaultRandom(),
    updatedById: uuid("updated_by_id").references(() => users.id, {
      onDelete: "set null",
    }),
    updatedAt: updatedAt(),
  },
  (t) => [check("site_settings_singleton_chk", sql`${t.id} = 1`)],
);

const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => "bytea",
});

/** Private file store used by STORAGE_DRIVER=database (default): photos never live on a public CDN. */
export const storedFiles = pgTable("stored_files", {
  key: varchar("key", { length: 255 }).primaryKey(),
  content: bytea("content").notNull(),
  contentType: varchar("content_type", { length: 80 }).notNull(),
  size: integer("size").notNull(),
  createdAt: createdAt(),
});

