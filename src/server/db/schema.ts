/**
 * Kinetic — relational database schema (PostgreSQL, Drizzle ORM).
 *
 * Design rules
 * ─────────────
 * • Every public-facing identifier is a random UUID (never sequential).
 * • Every client-owned row carries a `client_id` FK → clients.id (ON DELETE CASCADE),
 *   so authorization can always be expressed as `WHERE id = $1 AND client_id = $2`.
 * • Plans (workout_*, nutrition_*, meals, meal_items) are the *editable template*.
 *   Logs (workout_logs, workout_exercise_logs, workout_set_logs, meal_logs) are
 *   *immutable snapshots* of the template taken on the day. Editing a plan never
 *   rewrites history: log rows copy names/targets and reference the template with
 *   ON DELETE SET NULL only.
 * • All timestamps are `timestamptz` generated by the server. Calendar days are stored
 *   as `date` computed in the coach's configured IANA timezone.
 */
